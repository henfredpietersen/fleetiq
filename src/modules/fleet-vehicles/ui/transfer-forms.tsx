"use client";

import { useActionState } from "react";
import { Button } from "@/components/ui/button";
import { idle } from "../domain/action-state";
import {
  archiveVehicleAction,
  cancelTransferAction,
  decideTransferAction,
  requestTransferAction,
} from "../server/actions";
import {
  Field,
  FormMessage,
  SelectField,
  SubmitButton,
  TextareaField,
} from "./form-parts";

/** Request a branch transfer. Only creates an approval request: the vehicle does not move (DEC-31). */
export function RequestTransferForm({
  vehicleId,
  destinations,
  submissionId,
}: {
  vehicleId: string;
  destinations: { id: string; name: string }[];
  /** Generated by the server page per render: a double-click or retry is the same submission (idempotent). */
  submissionId: string;
}) {
  const [state, action, pending] = useActionState(requestTransferAction, idle);
  return (
    <form action={action} className="flex flex-col gap-4" noValidate>
      <input type="hidden" name="vehicleId" value={vehicleId} />
      <input type="hidden" name="clientSubmissionId" value={submissionId} />
      <SelectField
        id="toBranchId"
        label="Destination branch"
        required
        defaultValue=""
        disabled={pending}
      >
        <option value="" disabled>
          Choose a branch…
        </option>
        {destinations.map((b) => (
          <option key={b.id} value={b.id}>
            {b.name}
          </option>
        ))}
      </SelectField>
      <TextareaField
        id="reason"
        label="Reason"
        maxLength={1000}
        required
        disabled={pending}
      />
      <FormMessage state={state} />
      <div>
        <SubmitButton pending={pending} pendingLabel="Requesting…">
          Request transfer
        </SubmitButton>
      </div>
    </form>
  );
}

/** Approve / reject. The database refuses the requester and anyone without vehicle.transfer.approve. */
export function DecisionForm({ approvalId }: { approvalId: string }) {
  const [state, action, pending] = useActionState(decideTransferAction, idle);
  return (
    <form action={action} className="flex flex-col gap-3" noValidate>
      <input type="hidden" name="approvalId" value={approvalId} />
      <Field
        id="notes"
        label="Notes (optional)"
        maxLength={1000}
        disabled={pending}
      />
      <FormMessage state={state} />
      <div className="flex flex-wrap gap-3">
        <Button
          type="submit"
          name="decision"
          value="approved"
          disabled={pending}
          aria-busy={pending}
        >
          {pending ? "Working…" : "Approve transfer"}
        </Button>
        <Button
          type="submit"
          name="decision"
          value="rejected"
          variant="outline"
          disabled={pending}
        >
          Reject
        </Button>
      </div>
    </form>
  );
}

export function CancelTransferForm({ approvalId }: { approvalId: string }) {
  const [state, action, pending] = useActionState(cancelTransferAction, idle);
  return (
    <form action={action} className="flex flex-col gap-3">
      <input type="hidden" name="approvalId" value={approvalId} />
      <FormMessage state={state} />
      <div>
        <Button type="submit" variant="outline" disabled={pending}>
          {pending ? "Cancelling…" : "Cancel my request"}
        </Button>
      </div>
    </form>
  );
}

export function ArchiveForm({
  vehicleId,
  archived,
}: {
  vehicleId: string;
  archived: boolean;
}) {
  const [state, action, pending] = useActionState(archiveVehicleAction, idle);
  return (
    <form action={action} className="flex flex-col gap-3">
      <input type="hidden" name="id" value={vehicleId} />
      <input
        type="hidden"
        name="archived"
        value={archived ? "false" : "true"}
      />
      <FormMessage state={state} />
      <div>
        <Button type="submit" variant="outline" disabled={pending}>
          {pending
            ? "Working…"
            : archived
              ? "Restore vehicle"
              : "Archive vehicle"}
        </Button>
      </div>
    </form>
  );
}

// Generates supabase/tests/database/phase5a_validation_vectors.test.sql from the shared fixture
// (src/modules/odometer-mileage/domain/validation.fixture.json). Run: node scripts/gen-odometer-validation-test.mjs
// The SAME vectors run against the TypeScript mirror (validation.test.ts) and the SQL function odometer_evaluate_checks().
import { readFileSync, writeFileSync } from "node:fs";

const fx = JSON.parse(
  readFileSync(
    new URL(
      "../src/modules/odometer-mileage/domain/validation.fixture.json",
      import.meta.url,
    ),
    "utf8",
  ),
);
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = [];
for (const c of fx.cases) {
  const call = `public.odometer_evaluate_checks(${q(JSON.stringify(c.input))}::jsonb)`;
  lines.push(
    `select is((select jsonb_object_agg(k ->> 'key', k ->> 'result') from jsonb_array_elements(${call} -> 'checks') k), ${q(JSON.stringify(c.expect.results))}::jsonb, ${q(`${c.name}: results`)});`,
  );
  lines.push(
    `select is(${call} ->> 'route', ${q(c.expect.route)}, ${q(`${c.name}: route`)});`,
  );
  for (const [key, vals] of Object.entries(c.expect.values ?? {})) {
    for (const [name, v] of Object.entries(vals)) {
      lines.push(
        `select is((select k -> 'values' ->> ${q(name)} from jsonb_array_elements(${call} -> 'checks') k where k ->> 'key' = ${q(key)}), ${q(String(v))}, ${q(`${c.name}: ${key}.${name}`)});`,
      );
    }
  }
}
const out = `-- GENERATED by scripts/gen-odometer-validation-test.mjs from validation.fixture.json — do not edit by hand.
-- Slice 5A: odometer_evaluate_checks(), the reading validation rules (PRD v1.20 §5.8.8; DEC-12..DEC-17, DEC-44).
-- The same vectors run against the TypeScript mirror (src/modules/odometer-mileage/domain/validation.test.ts).
begin;
create extension if not exists pgtap with schema extensions;
select plan(${lines.length});
${lines.join("\n")}
select * from finish();
rollback;
`;
writeFileSync(
  new URL(
    "../supabase/tests/database/phase5a_validation_vectors.test.sql",
    import.meta.url,
  ),
  out,
);
console.log(`wrote ${lines.length} assertions`);
